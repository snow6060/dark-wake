-- Dark Wake initial Supabase schema.
-- Run in the Supabase SQL Editor for a new project before starting the app.
-- The backend uses the service-role key; do not expose it to the frontend.

begin;

create table if not exists public.chokepoint_records (
    id integer generated by default as identity primary key,
    date date not null,
    chokepoint_name text not null,
    portid text,
    vessel_count_total numeric,
    vessel_count_tanker numeric,
    vessel_count_container numeric,
    baseline_avg numeric,
    deviation_pct numeric,
    created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.vessels (
    id integer generated by default as identity primary key,
    mmsi text not null unique,
    ship_name text,
    ship_type text,
    dwt numeric,
    latitude numeric,
    longitude numeric,
    destination text,
    origin text,
    last_seen timestamptz,
    is_dark boolean default false,
    updated_at timestamptz not null default timezone('utc', now()),
    length_m real,
    beam_m real,
    imo text,
    callsign text,
    static_updated_at timestamptz
);

create table if not exists public.dark_fleet_logs (
    id integer generated by default as identity primary key,
    mmsi text not null,
    ship_name text,
    chokepoint_name text,
    disappearance_time timestamptz,
    reappearance_time timestamptz,
    gap_duration_minutes integer,
    created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.news_headlines (
    id bigint generated by default as identity primary key,
    title text not null,
    source text not null,
    link text not null unique,
    sentiment text not null,
    time_ago text default 'Just now',
    created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.transponder_events (
    id integer generated by default as identity primary key,
    vessel_id integer references public.vessels(id),
    event_type varchar not null,
    lat numeric,
    lng numeric,
    event_time timestamptz default now(),
    notes text
);

create table if not exists public.chokepoint_transits (
    id integer generated by default as identity primary key,
    vessel_id integer references public.vessels(id),
    chokepoint_name varchar not null,
    transit_status varchar default 'UNVERIFIED',
    was_dark boolean default false,
    ai_verdict_reasoning text,
    crossed_at timestamptz default now()
);

create table if not exists public.market_prices (
    id integer generated by default as identity primary key,
    symbol varchar not null unique,
    price numeric not null,
    change_pct numeric not null,
    history jsonb,
    updated_at timestamptz default now()
);

create table if not exists public.rss_news (
    id integer generated by default as identity primary key,
    title text not null,
    source varchar not null,
    link text,
    sentiment varchar default 'NEUTRAL',
    time_ago varchar,
    created_at timestamptz default now(),
    summary text
);

create table if not exists public.chokepoint_telemetry (
    id integer generated by default as identity primary key,
    chokepoint_name varchar not null,
    date date not null,
    tankers integer not null,
    estimated_oil_flow numeric,
    source varchar default 'IMF PortWatch'
);

create table if not exists public.war_room_debates (
    id bigint generated by default as identity primary key,
    symbol text not null default 'BZ=F',
    market_price numeric not null,
    signal text not null check (signal in ('BUY', 'SELL', 'HOLD')),
    short_term_trend text not null,
    long_term_trend text not null,
    support numeric not null,
    resistance numeric not null,
    market_context jsonb not null,
    transcript jsonb not null,
    verdict jsonb not null,
    created_at timestamptz not null default now()
);

create table if not exists public.strategy_desk_predictions (
    id bigint generated by default as identity primary key,
    analysis_id text not null,
    symbol text not null,
    base_price double precision not null check (base_price > 0),
    predicted_direction text not null
        check (predicted_direction in ('UP', 'DOWN', 'NEUTRAL')),
    agent_predictions jsonb not null default '{}'::jsonb,
    evaluation_due_at timestamptz not null,
    actual_price double precision,
    actual_direction text
        check (actual_direction is null or actual_direction in ('UP', 'DOWN', 'NEUTRAL')),
    direction_correct boolean,
    agent_results jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    evaluated_at timestamptz,
    unique (analysis_id, symbol)
);

create index if not exists strategy_desk_predictions_pending_idx
    on public.strategy_desk_predictions (evaluation_due_at)
    where evaluated_at is null;

create table if not exists public.strategy_desk_agent_accuracy (
    agent_name text primary key,
    evaluated_predictions integer not null default 0
        check (evaluated_predictions >= 0),
    correct_predictions integer not null default 0
        check (correct_predictions >= 0),
    accuracy numeric(5, 4) not null default 0
        check (accuracy >= 0 and accuracy <= 1),
    updated_at timestamptz not null default now()
);

create table if not exists public.spatial_zones (
    zone_id text primary key,
    display_name text not null,
    kind text not null
        check (kind in ('chokepoint', 'anchorage', 'terminal', 'hub', 'custom')),
    why_it_matters text not null,
    bbox_west double precision not null,
    bbox_south double precision not null,
    bbox_east double precision not null,
    bbox_north double precision not null,
    analysis_polygon jsonb,
    ref_lat double precision not null,
    ref_lon double precision not null,
    range_rings_km jsonb not null default '[5, 10, 20]'::jsonb,
    min_declared_length_m integer not null default 100,
    sort_order integer not null default 0,
    active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.spatial_snapshots (
    id integer generated by default as identity primary key,
    location_name varchar,
    image_url text not null,
    captured_at timestamptz default now(),
    zone_id text references public.spatial_zones(zone_id),
    scene_id text,
    source text not null default 'sentinel-2-l2a',
    acquired_at timestamptz,
    cloud_pct real,
    valid_pct real,
    gsd_m real not null default 10,
    crs text,
    window_transform jsonb,
    width_px integer,
    height_px integer,
    image_path text,
    thumb_path text,
    status text not null default 'fetched'
        check (status in ('fetched', 'analyzing', 'verified', 'failed')),
    analysis_started_at timestamptz,
    analyzed_at timestamptz,
    error text,
    created_at timestamptz not null default now(),
    tile_ids jsonb
);

create unique index if not exists spatial_snapshots_zone_scene_uidx
    on public.spatial_snapshots (zone_id, scene_id);
create index if not exists spatial_snapshots_zone_acquired_idx
    on public.spatial_snapshots (zone_id, acquired_at desc);

create table if not exists public.ais_positions (
    id bigint generated by default as identity primary key,
    mmsi text not null,
    zone_id text references public.spatial_zones(zone_id),
    lat double precision not null,
    lon double precision not null,
    sog_knots real,
    cog_deg real,
    heading_deg real,
    nav_status integer,
    reported_at timestamptz not null,
    created_at timestamptz not null default now()
);

create table if not exists public.vessel_verifications (
    id bigint generated by default as identity primary key,
    snapshot_id integer not null references public.spatial_snapshots(id),
    zone_id text not null references public.spatial_zones(zone_id),
    mmsi text not null,
    ship_name text,
    declared_type text,
    declared_length_m real,
    ais_reported_at timestamptz,
    ais_time_offset_s integer,
    predicted_lat double precision,
    predicted_lon double precision,
    observed_lat double precision,
    observed_lon double precision,
    position_offset_m real,
    measured_length_m real,
    measured_width_m real,
    sam_score real,
    mask_polygon jsonb,
    verdict text not null
        check (verdict in ('VERIFIED', 'SIZE_MISMATCH', 'NO_VESSEL_AT_CLAIM', 'NOT_OBSERVABLE')),
    reason text,
    created_at timestamptz not null default now()
);

create table if not exists public.unmatched_detections (
    id bigint generated by default as identity primary key,
    snapshot_id integer not null references public.spatial_snapshots(id),
    zone_id text not null references public.spatial_zones(zone_id),
    lat double precision not null,
    lon double precision not null,
    length_m real,
    width_m real,
    heading_deg real,
    sam_score real,
    ais_coverage text not null check (ais_coverage in ('COVERED', 'SPARSE', 'NONE')),
    label text not null check (label in ('UNMATCHED_AIS_COVERED', 'UNVERIFIED_SPARSE_AIS')),
    mask_polygon jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.spatial_zone_summaries (
    snapshot_id integer primary key references public.spatial_snapshots(id),
    zone_id text not null references public.spatial_zones(zone_id),
    acquired_at timestamptz not null,
    cloud_pct real,
    claims_total integer not null default 0,
    claims_observable integer not null default 0,
    verified integer not null default 0,
    size_mismatch integer not null default 0,
    no_vessel_at_claim integer not null default 0,
    not_observable integer not null default 0,
    unmatched_ais_covered integer not null default 0,
    unverified_sparse_ais integer not null default 0,
    verification_rate real,
    ais_messages_in_window integer,
    summary_core text not null,
    computed_at timestamptz not null default now()
);

create table if not exists public.spatial_analysis (
    snapshot_id integer primary key
        references public.spatial_snapshots(id) on delete cascade,
    zone_id text not null references public.spatial_zones(zone_id),
    scene_id text not null,
    acquired_at timestamptz not null,
    summary jsonb not null,
    hulls jsonb not null,
    flags jsonb not null,
    method text not null,
    computed_at timestamptz not null default now(),
    ais_vessels jsonb not null default '[]'::jsonb
);

create table if not exists public.spatial_startup_state (
    startup_key text primary key,
    status text not null check (status in ('pending', 'running', 'complete', 'failed')),
    started_at timestamptz,
    completed_at timestamptz,
    error text
);

create index if not exists ais_positions_zone_reported_idx
    on public.ais_positions (zone_id, reported_at desc);

alter table public.chokepoint_records enable row level security;
alter table public.vessels enable row level security;
alter table public.dark_fleet_logs enable row level security;
alter table public.news_headlines enable row level security;
alter table public.transponder_events enable row level security;
alter table public.chokepoint_transits enable row level security;
alter table public.market_prices enable row level security;
alter table public.rss_news enable row level security;
alter table public.chokepoint_telemetry enable row level security;
alter table public.war_room_debates enable row level security;
alter table public.strategy_desk_predictions enable row level security;
alter table public.strategy_desk_agent_accuracy enable row level security;
alter table public.spatial_zones enable row level security;
alter table public.spatial_snapshots enable row level security;
alter table public.ais_positions enable row level security;
alter table public.vessel_verifications enable row level security;
alter table public.unmatched_detections enable row level security;
alter table public.spatial_zone_summaries enable row level security;
alter table public.spatial_analysis enable row level security;
alter table public.spatial_startup_state enable row level security;

commit;
